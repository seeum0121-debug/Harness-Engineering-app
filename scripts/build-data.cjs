const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'content/catalog.json'), 'utf8'));
const sources = new Map(catalog.sources.map(s => [s.id, s]));
const files = fs.readdirSync(path.join(root, 'content')).filter(f => /^chapters-.*\.json$/.test(f)).sort();
assert(files.length === 3, 'Expected all three authored chapter files.');
const cards = [], questions = [], ids = new Set();
const validText = (text, label) => assert(typeof text === 'string' && text.trim().length > 0, label);
function checkPages(pages, source, label) {
  assert(Array.isArray(pages) && pages.length > 0, `${label}: missing pages`);
  pages.forEach(p => assert(Number.isInteger(p) && p >= 1 && p <= source.pages, `${label}: invalid page ${p}`));
}
for (const file of files) {
  const rows = JSON.parse(fs.readFileSync(path.join(root, 'content', file), 'utf8'));
  assert(Array.isArray(rows));
  for (const raw of rows) {
    const id = `ch${raw.chapter}-${raw.id}`;
    assert(/^[a-zA-Z0-9-]+$/.test(id), `Invalid ID ${id}`);
    assert(!ids.has(id), `Duplicate ${id}`); ids.add(id);
    const source = sources.get(raw.source?.fileId);
    assert(source && source.chapters.includes(raw.chapter), `Source/chapter mismatch: ${id}`);
    for (const key of ['name','drugClass','moa','uses']) validText(raw[key], `${id}: ${key}`);
    checkPages(raw.source.pages, source, id);
    const qByType = new Map(raw.questions.map(q => [q.type, q]));
    for (const type of ['moa','use']) {
      const q = qByType.get(type);
      assert(q && q.choices.length === 4 && new Set(q.choices).size === 4, `${id}: ${type} options`);
      q.choices.forEach(c => validText(c, `${id}: empty option`));
      assert(Number.isInteger(q.answer) && q.answer >= 0 && q.answer < 4, `${id}: answer`);
      validText(q.explanation, `${id}: explanation`);
      checkPages(q.sourcePages, source, `${id} ${type}`);
    }
    const ab = raw.ab;
    assert(ab && ab.truth.length === 2 && ab.truth.every(v => typeof v === 'boolean'), `${id}: missing AB truth`);
    for (const key of ['a','b','explanation']) validText(ab[key], `${id}: AB ${key}`);
    assert(ab.a !== ab.b, `${id}: identical statements`);
    checkPages(ab.sourcePages, source, `${id} AB`);
    const moa = qByType.get('moa'), use = qByType.get('use');
    const {questions: unused, ab: unusedAB, ...card} = raw;
    cards.push({...card, id});
    questions.push({id:`${id}-match`, cardId:id, chapter:raw.chapter, type:'match',
      moa:{choices:moa.choices,answer:moa.answer}, use:{choices:use.choices,answer:use.answer},
      explanation:`작용기전: ${moa.explanation}\n용도: ${use.explanation}`,
      source:{fileId:source.id,pages:[...new Set([...moa.sourcePages,...use.sourcePages])].sort((a,b)=>a-b)}});
    questions.push({id:`${id}-ab`,cardId:id,chapter:raw.chapter,type:'ab',a:ab.a,b:ab.b,
      truth:ab.truth,answer:ab.truth[0]?(ab.truth[1]?2:0):(ab.truth[1]?1:3),explanation:ab.explanation,
      source:{fileId:source.id,pages:ab.sourcePages}});
  }
}
for (const ch of catalog.chapters) assert(cards.some(c => c.chapter === ch.id), `Missing chapter ${ch.id}`);
const data = {...catalog,cards,questions};
fs.mkdirSync(path.join(root,'dist/data'),{recursive:true});
fs.writeFileSync(path.join(root,'dist/data/question-bank.js'), `/* Generated by npm run build. Edit content/*.json instead. */\nwindow.PHARM_DATA = ${JSON.stringify(data)};\n`);
console.log(`Validated ${cards.length} drug cards, ${questions.length} questions, ${catalog.chapters.length} chapters, ${catalog.sources.length} PDFs.`);
